package com.example.festnav;

public class EventGoersResponse {
    private int id_event_goers;
    private String nama;
    private String username;
    private String email;
    private String nomor_telepon;
    private String dibuat_pada;

    public int getId_event_goers() { return id_event_goers; }
    public String getNama() { return nama; }
    public String getUsername() { return username; }
    public String getEmail() { return email; }
    public String getNomor_telepon() { return nomor_telepon; }
    public String getDibuat_pada() { return dibuat_pada; }
}